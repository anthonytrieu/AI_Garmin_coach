import { chromium } from 'playwright'
import assert from 'node:assert/strict'
const personal = process.env.TRACKING_TEST_URL ?? 'http://127.0.0.1:5184'
const demo = process.env.DEMO_TEST_URL ?? 'http://127.0.0.1:5183'
if (!['127.0.0.1', 'localhost'].includes(new URL(personal).hostname)) throw Error('Personal logging tests require disposable local storage; production is forbidden.')
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage(), errors = [], chatCalls = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/api/chat/conversations', route => route.fulfill({ json: [] }))
  await page.route('**/api/chat', route => { chatCalls.push(route.request().postData()); return route.fulfill({ contentType: 'text/event-stream', body: 'data: {"type":"text","text":"Synthetic coaching reply"}\n\ndata: {"type":"done"}\n\n' }) })
  const records = async kind => (await (await context.request.get(personal + '/api/tracking')).json()).records.filter(r => r.kind === kind && r.data)
  assert.equal((await records('meal')).length, 0, 'Use an empty synthetic API')
  const send = async text => { await page.getByLabel('Message your coach').fill(text); await page.getByRole('button', { name: 'Send', exact: true }).click() }
  await page.goto(personal + '/coach')
  await send('I ate a jr chicken from mcdonalds add that to the meals today')
  assert.equal(await page.getByLabel('Calories per portion', { exact: true }).inputValue(), '380')
  assert.equal(await page.getByLabel('Protein per portion · g', { exact: true }).inputValue(), '12')
  for (const width of [320, 390, 1280]) {
    await page.setViewportSize({ width, height: 844 }); await page.waitForTimeout(100)
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  }
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal((await records('meal')).length, 0)
  await send('I ate two jr chickens from mcdonalds')
  await page.getByRole('button', { name: 'Add meal', exact: true }).click()
  await page.getByRole('heading', { name: 'Meal added', exact: true }).waitFor()
  assert.equal((await records('meal'))[0].data.calories, 760)
  assert.equal((await records('meal'))[0].data.protein, 24)
  await page.reload()
  await page.getByRole('heading', { name: 'Meal added', exact: true }).waitFor()
  assert.equal((await records('meal')).length, 1)
  await page.getByRole('button', { name: 'Undo meal', exact: true }).click()
  await page.getByRole('heading', { name: 'Entry removed', exact: true }).waitFor()
  assert.equal((await records('meal')).length, 0)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await send('I ate lunch 500 calories 30g protein')
  let dropped = false
  await page.route('**/api/tracking/meal/*', async route => {
    if (!dropped && route.request().method() === 'PUT') { dropped = true; await route.fetch(); await route.abort(); return }
    await route.continue()
  })
  await page.getByRole('button', { name: 'Add meal', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'retained' }).waitFor()
  await page.reload()
  await page.getByRole('heading', { name: 'Meal added', exact: true }).waitFor()
  assert.equal((await records('meal')).length, 1, 'Lost response and refresh must not duplicate the meal')
  await page.unroute('**/api/tracking/meal/*')
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await send('I ate lunch 500 calories 30g protein')
  assert(await page.getByRole('button', { name: 'Add meal', exact: true }).isDisabled())
  await page.getByRole('checkbox', { name: /matching entry/ }).check()
  assert(await page.getByRole('button', { name: 'Add meal', exact: true }).isEnabled())
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await send('I biked for 40 minutes, add that to today')
  await page.getByRole('button', { name: 'Save ride', exact: true }).click()
  await page.getByRole('heading', { name: 'Ride saved', exact: true }).waitFor()
  assert.equal((await records('ride'))[0].data.minutes, 40)
  await page.getByRole('button', { name: 'Undo ride', exact: true }).click()
  await page.getByRole('heading', { name: 'Entry removed', exact: true }).waitFor()
  assert.equal((await records('ride')).length, 0)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await send('I ate chicken')
  assert.equal(await page.getByLabel('Calories per portion', { exact: true }).inputValue(), '')
  await page.getByRole('button', { name: 'Add meal', exact: true }).click()
  assert.equal((await records('meal')).length, 1, 'Unknown foods need nutrition and quantity')
  await page.route('**/api/nutrition/search?*', route => route.fulfill({ json: { items: [{ id: 'off-12345678', name: 'Synthetic oats', calories: 400, protein: 12, portion: '100 g', source: 'Open Food Facts · test fixture', url: 'https://world.openfoodfacts.org/product/12345678' }] } }))
  await page.getByRole('button', { name: 'Search packaged foods', exact: true }).click()
  await page.getByRole('button', { name: /Synthetic oats/ }).click()
  await page.getByLabel('Number of portions').fill('1.5')
  await page.getByRole('button', { name: 'Add meal', exact: true }).click()
  await page.getByRole('heading', { name: 'Meal added', exact: true }).waitFor()
  const oats = (await records('meal')).find(r => r.data.name === 'Synthetic oats')
  assert.equal(oats.data.calories, 600); assert.equal(oats.data.protein, 18)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await send('I ate a sandwich tomorrow')
  assert.equal(await page.getByLabel('Meal date', { exact: true }).inputValue(), '')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await send('How should I train today?')
  await page.getByText('Synthetic coaching reply', { exact: true }).waitFor()
  assert.equal(chatCalls.length, 1, 'Logging requests must not invoke the AI coach')
  await context.close()
  const dp = await browser.newPage({ viewport: { width: 390, height: 844 } }), calls = []
  dp.on('request', r => { if (new URL(r.url()).pathname.startsWith('/api/')) calls.push(r.url()) })
  dp.on('pageerror', e => errors.push(e.message))
  await dp.goto(demo + '/coach')
  await dp.getByText(/Portfolio demo/).waitFor()
  await dp.getByRole('button', { name: 'Log a sample meal', exact: true }).click()
  await dp.getByRole('button', { name: 'Add meal', exact: true }).click()
  await dp.getByRole('heading', { name: 'Meal added', exact: true }).waitFor()
  await dp.getByRole('button', { name: 'Undo meal', exact: true }).click()
  await dp.getByRole('heading', { name: 'Entry removed', exact: true }).waitFor()
  assert.deepEqual(calls, [], 'Demo must not call private APIs')
  assert.deepEqual(errors, [], 'Browser runtime errors')
  console.log('Coach logging browser checks passed: meal quantities/totals, confirmation/cancel, saved refresh, lost-response recovery, duplicate guard, ride save/undo, unknown food validation, sourced lookup, dates, AI separation, responsive dialogs and demo isolation.')
} finally { await browser.close() }
